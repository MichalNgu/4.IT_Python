def path_exists(graph, start, end):
    to_visit = Stack()
    visited = Stack()
    to_visit.push(start)
    while to_visit.size() > 0:
        act = to_visit.pop()
        if act == end:
            return True
        if not visited.is_in(act):
            visited.push(act)
            for next in range(len(graph[act])):
                if graph[act][next] == 1:
                    if not to_visit.is_in(next) and not visited.is_in(next):
                        to_visit.push(next)
    return False
 
